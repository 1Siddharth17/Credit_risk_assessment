"""##  3. Business Interpretation

### Which Metric Matters Most, and Why?

In credit risk, **Recall (Sensitivity) is the most critical metric**.

**Recall** measures: *Of all actual defaulters, how many did we correctly identify?*

A missed defaulter (False Negative) is far more costly than a wrongly flagged good customer (False Positive):

### Cost of Errors

| Error Type | Scenario | Business Cost |
|-----------|----------|---------------|
| **False Negative** (missed default) | We approve a bad borrower | Full loan loss (e.g., €5,000–€18,000) + collection costs |
| **False Positive** (wrongly rejected) | We reject a good borrower | Lost interest revenue (€300–€1,500) + customer acquisition cost |

**The asymmetry is clear:** A missed defaulter costs ~10x more than a missed good customer. This justifies optimizing primarily for Recall.

### Recommended Threshold for Production

We recommend a **decision threshold of 0.40** (instead of the default 0.50) to push Recall above 75% while keeping Precision acceptable. This can be adjusted based on the institution's risk appetite:
- **Conservative (high recall):** threshold = 0.35 → Recall ~80%, Precision drops
- **Balanced:** threshold = 0.40 → Recall ~75–78%
- **Aggressive (high precision):** threshold = 0.50 → Recall ~65%, Precision high
"""

# ── Threshold Analysis for Best Model ──
y_prob_best = best_model.predict_proba(X_test)[:, 1]
thresholds_test = np.arange(0.3, 0.7, 0.05)

threshold_results = []
for t in thresholds_test:
    y_pred_t = (y_prob_best >= t).astype(int)
    threshold_results.append({
        'Threshold': round(t, 2),
        'Precision': round(precision_score(y_test, y_pred_t, zero_division=0), 3),
        'Recall':    round(recall_score(y_test, y_pred_t), 3),
        'F1':        round(f1_score(y_test, y_pred_t), 3)
    })

threshold_df = pd.DataFrame(threshold_results)
print(f'=== Threshold Analysis — {best_model_name} ===')
print(threshold_df.to_string(index=False))

# Highlight 75% recall row
above_75 = threshold_df[threshold_df['Recall'] >= 0.75]
if not above_75.empty:
    rec_thresh = above_75.iloc[-1]
    print(f'\n Recommended threshold: {rec_thresh["Threshold"]} → Recall={rec_thresh["Recall"]}')

